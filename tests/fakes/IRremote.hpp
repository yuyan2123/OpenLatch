#pragma once
#include <cstdint>
enum decode_type_t { UNKNOWN, PULSE_WIDTH, PULSE_DISTANCE, APPLE, DENON, JVC, LG, LG2,
  NEC, NEC2, ONKYO, PANASONIC, KASEIKYO, KASEIKYO_DENON, KASEIKYO_SHARP, KASEIKYO_JVC,
  KASEIKYO_MITSUBISHI, RC5, RC6, RC6A, SAMSUNG, SAMSUNGLG, SAMSUNG48, SHARP, SONY };
constexpr uint8_t IRDATA_FLAGS_IS_REPEAT = 0x01, IRDATA_FLAGS_IS_AUTO_REPEAT = 0x02,
  IRDATA_FLAGS_PARITY_FAILED = 0x04, IRDATA_FLAGS_TOGGLE_BIT = 0x08,
  IRDATA_FLAGS_EXTRA_INFO = 0x10, IRDATA_FLAGS_WAS_OVERFLOW = 0x40;
struct IRData {
  decode_type_t protocol = UNKNOWN;
  uint16_t address = 0, command = 0, numberOfBits = 0;
  uint8_t flags = 0;
};
