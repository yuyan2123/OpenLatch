"""Embed the standalone setup page into the ESP32 firmware without runtime assets."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "firmware/OpenLatch/web/index.html"
TARGET = ROOT / "firmware/OpenLatch/SetupPage.h"


def main():
    page = SOURCE.read_text(encoding="utf-8")
    # Keep the device page self-contained; no stylesheet fetch is needed on ESP32.
    page = page.replace('@import url("tokens.css");',
                        (SOURCE.parent / "tokens.css").read_text(encoding="utf-8"))
    if ')SETUPPAGE"' in page:
        raise ValueError("Setup page contains the reserved C++ raw-string delimiter.")
    output = ('// Generated by tools/build_setup_page.py. Edit web/index.html instead.\n'
              '#pragma once\n#include <pgmspace.h>\n'
              'static const char kSetupPage[] PROGMEM = R"SETUPPAGE(' + page + ')SETUPPAGE";\n')
    if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != output:
        TARGET.write_text(output, encoding="utf-8")


if __name__ == "__main__":
    main()
